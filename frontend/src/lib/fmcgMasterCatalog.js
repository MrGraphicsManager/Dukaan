/**
 * Fast lookup helper for barcode scanning
 * Matches exact barcode string or partial barcode
 */
export function findFMCGByBarcode(barcode) {
  if (!barcode) return null;
  const clean = String(barcode).trim();
  return FMCG_MASTER_CATALOG.find(item => item.barcode === clean) || null;
}

/**
 * Search helper across FMCG catalog by name, category, or barcode
 */
export function searchFMCGCatalog(query, limit = 20) {
  if (!query || !query.trim()) return FMCG_MASTER_CATALOG.slice(0, limit);
  const q = query.toLowerCase().trim();
  return FMCG_MASTER_CATALOG.filter(item => 
    item.name.toLowerCase().includes(q) ||
    item.barcode.includes(q) ||
    item.category.toLowerCase().includes(q)
  ).slice(0, limit);
}
