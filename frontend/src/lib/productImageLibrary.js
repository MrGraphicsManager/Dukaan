export function getProductLetterBadge(name) {
  if (!name || typeof name !== "string") {
    return {
      letter: "P",
      ...COLOR_PALETTES[2] // default blue
    };
  }

  const clean = name.trim();
  const letter = clean[0]?.toUpperCase() || "P";

  // Deterministic DJB2 hash of the product name
  let hash = 5381;
  for (let i = 0; i < clean.length; i++) {
    hash = ((hash << 5) + hash) + clean.charCodeAt(i);
  }

  const paletteIndex = Math.abs(hash) % COLOR_PALETTES.length;
  const palette = COLOR_PALETTES[paletteIndex];

  return {
    letter,
    ...palette
  };
}
