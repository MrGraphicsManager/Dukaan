const STORAGE_KEY = "dukaan_image_library";

// Retrieve all images in library (Default + Admin Added)
export function getLibraryImages() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return DEFAULT_IMAGE_LIBRARY;
    const custom = JSON.parse(raw);
    if (!Array.isArray(custom)) return DEFAULT_IMAGE_LIBRARY;

    // Merge custom with default, avoiding duplicate IDs
    const merged = [...DEFAULT_IMAGE_LIBRARY];
    custom.forEach(item => {
      const idx = merged.findIndex(m => m.id === item.id);
      if (idx >= 0) {
        merged[idx] = item;
      } else {
        merged.unshift(item);
      }
    });
    return merged;
  } catch {
    return DEFAULT_IMAGE_LIBRARY;
  }
}

// Admin function: Save or Update image in Library
export function saveLibraryImage(item) {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    const existing = raw ? JSON.parse(raw) : [];
    const id = item.id || `lib_custom_${Date.now()}_${Math.floor(Math.random() * 1000)}`;
    const newItem = { ...item, id };
    
    const idx = existing.findIndex(x => x.id === id);
    let updated;
    if (idx >= 0) {
      updated = [...existing];
      updated[idx] = newItem;
    } else {
      updated = [newItem, ...existing];
    }
    
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
    window.dispatchEvent(new CustomEvent("dukaan_image_library_updated", { detail: updated }));
    return newItem;
  } catch (err) {
    console.error("Failed to save library image:", err);
    return null;
  }
}

// Admin function: Delete image from Library
export function deleteLibraryImage(id) {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    const existing = raw ? JSON.parse(raw) : [];
    const filtered = existing.filter(x => x.id !== id);
    localStorage.setItem(STORAGE_KEY, JSON.stringify(filtered));
    window.dispatchEvent(new CustomEvent("dukaan_image_library_updated", { detail: filtered }));
    return true;
  } catch (err) {
    console.error("Failed to delete library image:", err);
    return false;
  }
}

// Automatically match a product name to an image in the library
export function findLibraryImage(productName) {
  if (!productName) return null;
  const q = productName.toLowerCase().trim();
  const library = getLibraryImages();
  
  // Exact name match
  const exact = library.find(item => item.name.toLowerCase() === q);
  if (exact) return exact.image_url;

  // Substring or tag match
  const partial = library.find(item => {
    if (q.includes(item.name.toLowerCase()) || item.name.toLowerCase().includes(q)) return true;
    return (item.tags || []).some(t => q.includes(t.toLowerCase()));
  });

  return partial ? partial.image_url : null;
}

